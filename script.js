/* =========================================================
   FUNCIONES GENERALES
========================================================= */

function normalizeText(text) {
  return String(text || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();
}


function escapeHTML(text) {
  const div = document.createElement("div");
  div.textContent = text;
  return div.innerHTML;
}


function getCategory(categoryName) {
  return catalogData.find(
    category => category.name === categoryName
  );
}


function setFooterVisible(visible) {
  if (!footerElement) return;

  footerElement.classList.toggle(
    "is-hidden",
    !visible
  );
}


function setBannerVisible(visible) {
  if (!infoBanner) return;

  infoBanner.hidden = !visible;
}


function updateSearchStatus(text = "") {
  if (!searchStatus) return;

  searchStatus.textContent = text;
}


/* =========================================================
   WHATSAPP
   60% ASESOR
   40% ASESORA
========================================================= */

function getWhatsAppNumber() {

  const random = Math.random();

  if (random < 0.60) {
    return WHATSAPP_ADVISOR;
  }

  return WHATSAPP_ADVISOR_2;
}


function openWhatsApp(productName = "") {

  const number = getWhatsAppNumber();

  let message =
    "Hola, quiero recibir información sobre ";

  if (productName) {
    message += productName;
  } else {
    message += "un producto del catálogo de Nexus";
  }

  message += ".";

  const url =
    `https://wa.me/${number}?text=${encodeURIComponent(message)}`;

  window.open(
    url,
    "_blank",
    "noopener,noreferrer"
  );
}


/* =========================================================
   IMÁGENES
========================================================= */

function handleImageError(image) {

  image.onerror = null;

  image.style.display = "none";

  const wrapper = image.parentElement;

  if (wrapper) {
    wrapper.classList.add("image-error");
  }
}


/* =========================================================
   CREAR CARD DE CATEGORÍA
========================================================= */

function createCategoryCard(category) {

  return `
    <article class="category-card">

      <div class="category-image-wrap">
        <img
          src="${category.image}"
          alt="${escapeHTML(category.name)}"
          loading="lazy"
          onerror="handleImageError(this)"
        >
      </div>

      <div class="category-content">

        <h3 class="category-title">
          ${escapeHTML(category.name)}
        </h3>

        <button
          type="button"
          class="explore-button"
          data-category="${escapeHTML(category.name)}"
        >
          Conocer productos
        </button>

      </div>

    </article>
  `;
}


/* =========================================================
   CREAR CARD DE SUBCATEGORÍA
========================================================= */

function createItemCard(item, categoryName) {

  return `
    <article class="subcategory-card">

      <div class="subcategory-title">
        ${escapeHTML(item.name)}
      </div>

      <div class="subcategory-image-wrap">
        <img
          src="${item.image}"
          alt="${escapeHTML(item.name)}"
          loading="lazy"
          onerror="handleImageError(this)"
        >
      </div>

      <div class="subcategory-actions">

        <button
          type="button"
          class="quote-button"
          data-product="${escapeHTML(item.name)}"
          data-category="${escapeHTML(categoryName)}"
        >
          Cotizar
        </button>

      </div>

    </article>
  `;
}


/* =========================================================
   RENDER - PÁGINA PRINCIPAL
========================================================= */

function renderCategories(options = {}) {

  const {
    updateHistory = true,
    scroll = false
  } = options;

  currentCategory = null;

  setBannerVisible(true);
  setFooterVisible(true);

  catalogTitle.textContent =
    "Encuentra lo que necesitas";

  updateSearchStatus("");

  const query =
    normalizeText(currentSearch);

  let filteredCategories =
    catalogData;

  if (query) {

    filteredCategories =
      catalogData.filter(category => {

        const categoryMatch =
          normalizeText(category.name)
            .includes(query);

        const itemMatch =
          category.items.some(item =>
            normalizeText(item.name)
              .includes(query)
          );

        return categoryMatch || itemMatch;
      });

  }

  catalogCount.textContent =
    query
      ? `${filteredCategories.length} ${filteredCategories.length === 1 ? "categoría" : "categorías"}`
      : "10 categorías";


  if (query) {

    updateSearchStatus(
      `Resultados para “${currentSearch}”`
    );

  }


  if (!filteredCategories.length) {

    catalogElement.innerHTML = `
      <div class="empty-state">

        <h3>No encontramos una categoría relacionada</h3>

        <p>
          Prueba con otro término o selecciona una categoría
          cercana a lo que estás buscando.
        </p>

      </div>
    `;

  } else {

    catalogElement.innerHTML =
      filteredCategories
        .map(createCategoryCard)
        .join("");

  }


  if (updateHistory) {

    history.pushState(
      {
        page: "home"
      },
      "",
      window.location.pathname
    );

  }


  if (scroll) {

    document.getElementById("catalogSection")
      ?.scrollIntoView({
        behavior:"smooth",
        block:"start"
      });

  }

}


/* =========================================================
   RENDER - CATEGORÍA
========================================================= */

function renderCategory(categoryName, options = {}) {

  const {
    updateHistory = true,
    scroll = true
  } = options;

  const category =
    getCategory(categoryName);

  if (!category) {
    renderCategories();
    return;
  }

  currentCategory =
    category.name;

  setBannerVisible(false);
  setFooterVisible(false);

  catalogTitle.textContent =
    category.name;


  const query =
    normalizeText(currentSearch);


  let filteredItems =
    category.items;


  if (query) {

    filteredItems =
      category.items.filter(item =>
        normalizeText(item.name)
          .includes(query)
      );

  }


  catalogCount.textContent =
    query
      ? `${filteredItems.length} ${filteredItems.length === 1 ? "opción" : "opciones"}`
      : `${category.items.length} opciones`;


  updateSearchStatus(
    query
      ? `Resultados para “${currentSearch}”`
      : ""
  );


  let content = "";


  if (!filteredItems.length) {

    content += `
      <div class="empty-state">

        <h3>No encontramos ese producto</h3>

        <p>
          Prueba con otro término o selecciona una opción
          similar. Un asesor de Nexus te ayudará a encontrar
          la alternativa que necesitas.
        </p>

      </div>
    `;

  } else {

    content += `
      <div class="subcategory-grid">

        ${filteredItems
          .map(item =>
            createItemCard(item, category.name)
          )
          .join("")}

      </div>
    `;

  }


  content += `
    <button
      type="button"
      class="back-to-catalog"
    >
      Volver al catálogo
    </button>
  `;


  catalogElement.innerHTML =
    content;


  if (updateHistory) {

    history.pushState(
      {
        page:"category",
        category:category.name
      },
      "",
      window.location.pathname
    );

  }


  if (scroll) {

    document.getElementById("catalogSection")
      ?.scrollIntoView({
        behavior:"smooth",
        block:"start"
      });

  }

}


/* =========================================================
   VOLVER AL CATÁLOGO
========================================================= */

function goBackToCatalog(options = {}) {

  const {
    updateHistory = true,
    scroll = true
  } = options;

  currentCategory = null;
  currentSearch = "";

  searchInput.value = "";

  if (updateHistory) {

    history.pushState(
      {
        page:"home"
      },
      "",
      window.location.pathname
    );

  }

  renderCategories({
    updateHistory:false,
    scroll:false
  });

  if (scroll) {

    document.getElementById("catalogSection")
      ?.scrollIntoView({
        behavior:"smooth",
        block:"start"
      });

  }

}


/* =========================================================
   BUSCADOR
========================================================= */

function performSearch() {

  currentSearch =
    searchInput.value.trim();


  if (currentCategory) {

    renderCategory(
      currentCategory,
      {
        updateHistory:false,
        scroll:false
      }
    );

  } else {

    renderCategories(
      {
        updateHistory:false,
        scroll:false
      }
    );

  }


  document.getElementById("catalogSection")
    ?.scrollIntoView({
      behavior:"smooth",
      block:"start"
    });

}


searchForm?.addEventListener(
  "submit",
  event => {

    event.preventDefault();

    performSearch();

  }
);


/* =========================================================
   EVENT DELEGATION
========================================================= */

catalogElement?.addEventListener(
  "click",
  event => {

    /* -----------------------------------------
       VOLVER AL CATÁLOGO
    ----------------------------------------- */

    const backButton =
      event.target.closest(
        ".back-to-catalog"
      );

    if (backButton) {

      event.preventDefault();

      goBackToCatalog();

      return;
    }


    /* -----------------------------------------
       ENTRAR A CATEGORÍA
    ----------------------------------------- */

    const categoryButton =
      event.target.closest(
        ".explore-button"
      );

    if (categoryButton) {

      event.preventDefault();

      const categoryName =
        categoryButton.dataset.category;

      renderCategory(
        categoryName
      );

      return;
    }


    /* -----------------------------------------
       COTIZAR
    ----------------------------------------- */

    const quoteButton =
      event.target.closest(
        ".quote-button"
      );

    if (quoteButton) {

      event.preventDefault();

      const product =
        quoteButton.dataset.product;

      const category =
        quoteButton.dataset.category;

      const number =
        getWhatsAppNumber();


      const message =
        `Hola, quiero cotizar ${product} de la categoría ${category}.`;


      const url =
        `https://wa.me/${number}?text=${encodeURIComponent(message)}`;


      window.open(
        url,
        "_blank",
        "noopener,noreferrer"
      );

    }

  }
);


